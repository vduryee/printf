#include "libft.h"

void	ft_lstiter(t_list *lst, void (*f)(void *))
{
	t_list	*iter;

	if (!lst || !f)
		return ;
	while (lst)
	{
		f(lst -> content);
		iter = lst -> next;
		lst = iter;
	}
}
